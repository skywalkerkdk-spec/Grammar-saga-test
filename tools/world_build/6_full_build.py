"""Full 6-panel continent: stitch GPT panels, derive walkable tiles from art, place sites, carve links, export world.js/world.webp."""
import numpy as np,json,heapq,os
from PIL import Image,ImageDraw
from scipy import ndimage as ndi
Image.MAX_IMAGE_PIXELS=None
G='/tmp/gs/worldmap/';OUT=os.environ.get('OUT','/tmp/w6')
T=24;COLS=192;ROWS=85;cell=12
names=[['north-west','north-center','north-east'],['south-west-syntaxbury','south-center-hand-painted-winding','south-east']]
M=Image.new('RGB',(4608,2048))
for r,row in enumerate(names):
    for c,f in enumerate(row):M.paste(Image.open(G+f+'.png').convert('RGB'),(c*1536,r*1024))
M=M.crop((0,0,4608,ROWS*T))
S=M.resize((COLS*cell,ROWS*cell),Image.BOX)
hsv=np.asarray(S.convert('HSV')).astype(float)
H=hsv[:,:,0]*360/255;Sa=hsv[:,:,1]/255;V=hsv[:,:,2]/255
water=(H>165)&(H<250)&(Sa>0.30)&(V>0.28)
road=(H>20)&(H<55)&(Sa>0.25)&(Sa<0.75)&(V>0.60)
cliff=(H<26)&(Sa>0.45)&(V>0.30)&(V<0.80)&~road
lava=(H<24)&(Sa>0.70)&(V>0.80)
dk=(H>45)&(H<160)&(V<0.52)&(Sa>0.35)
rock=(Sa<0.40)&(V>0.25)&(V<0.80)&~road
wheat=(H>38)&(H<62)&(Sa>0.55)&(V>0.7)
fr=lambda a:a.reshape(ROWS,cell,COLS,cell).mean((1,3))
blk=water|rock|cliff|lava
fb,fd,frd,fwh=fr(blk),fr(dk),fr(road),fr(wheat)
tw=~((fb>=0.35)|(fd>=0.30));tw|=frd>=0.18
# --- sites (brief positions /2, with manual fixes in SW panel)
S0=json.load(open('/tmp/gs/worldmap-brief/sites6.json'))
P={k:[v[1]//2,v[2]//2] for k,v in S0.items()}
# SW panel redrawn with Syntaxbury (d4) between the Quiet Wood and the Slime Cave; icon centres measured on the 1536x1024 art (+1024 for the south row)
P.update({'d1':[270,1024+495],'d4':[470,1024+490],'d2':[580,1024+320],'d3':[650,1024+735],'d5':[1245,1024+745],'d6':[1340,1024+190],'d7':[915,1024+170],'d8':[235,1024+195],'cv':[1125,1024+500]})
D={}
for f in ('1_CENTER','2_WEST','3_EAST'):
    for l in open(f'/tmp/wm6/old_{f}.md',encoding='utf8'):
        if l.startswith('|') and not l.startswith('|---') and not l.startswith('| id | place'):
            c=[x.strip() for x in l.strip().strip('|').split('|')];D[c[0].replace('(town)','_t')]=c[1]
D['d4']='Syntaxbury / 신택스베리';D['cv']="Merchants' Caravan / 상인의 카라반"
inv=~tw;lab,n=ndi.label(inv);sz=ndi.sum(inv,lab,range(1,n+1))
for i,s in enumerate(sz):
    if s<=2:tw[lab==i+1]=True
lab,n=ndi.label(tw);sz=ndi.sum(tw,lab,range(1,n+1))
for i,s in enumerate(sz):
    if s<25:tw[lab==i+1]=False
lab,n=ndi.label(tw);main=1+int(np.argmax(ndi.sum(tw,lab,range(1,n+1))))
def nearest_walk(x,y,r):
    best=None
    for dy in range(-r,r+1):
        for dx in range(-r,r+1):
            a,b=x+dx,y+dy
            if 0<=a<COLS and 0<=b<ROWS and tw[b,a]:
                d=dx*dx+dy*dy
                if best is None or d<best[0]:best=(d,a,b)
    return best
def carve(sx,sy):
    dist={(sx,sy):0};prev={};pq=[(0,sx,sy)]
    while pq:
        d,x,y=heapq.heappop(pq)
        if d>dist.get((x,y),1e9):continue
        if lab[y,x]==main and tw[y,x]:
            path=[];c=(x,y)
            while c in prev:path.append(c);c=prev[c]
            path.append((sx,sy));return path
        for dx,dy in((1,0),(-1,0),(0,1),(0,-1)):
            nx,ny=x+dx,y+dy
            if not(1<=nx<COLS-1 and 1<=ny<ROWS-1):continue
            nd=d+(1 if tw[ny,nx] else 6)
            if nd<dist.get((nx,ny),1e9):dist[(nx,ny)]=nd;prev[(nx,ny)]=(x,y);heapq.heappush(pq,(nd,nx,ny))
pts={};meta={};carved=[]
for k,(px,py) in P.items():
    tx,ty=px//T,min(py//T+1,ROWS-1)
    nw=nearest_walk(tx,ty,4) or nearest_walk(tx,ty,8)
    if nw is None:tw[ty,tx]=True;ex,ey=tx,ty
    else:ex,ey=nw[1],nw[2]
    lab,n=ndi.label(tw);main=1+int(np.argmax(ndi.sum(tw,lab,range(1,n+1))))
    if lab[ey,ex]!=main:
        p=carve(ex,ey)
        if p:
            for cx,cy in p:tw[cy,cx]=True
            carved.append((k,len(p)))
    pts[k]=[int(ex),int(ey)]
    en,ko=D[k].split(' / ') if k in D and ' / ' in D[k] else (k,k)
    meta[k]={'kind':'T' if S0[k][0]=='T' else 'D','en':en,'ko':ko}
lab,n=ndi.label(tw);main=1+int(np.argmax(ndi.sum(tw,lab,range(1,n+1))))
print('carved',carved);print('unreachable',[k for k,(x,y) in pts.items() if lab[y,x]!=main],'walk%',round(tw.mean()*100,1))
letters={'a':fwh>0.25,'f':fd>0.3,'h':fr(rock&~road)>0.25}
zt=np.full((ROWS,COLS),'g',dtype='<U1')
for l in 'hfa':zt[letters[l]]=l
yy,xx=np.mgrid[0:ROWS,0:COLS]
for k,(px,py) in pts.items():
    r=4 if k.endswith('_t') else 3;zt[(xx-px)**2+(yy-(py-1))**2<=r*r]='.'
sx,sy=pts['d4']
tiles=[''.join('.' if tw[y,x] else '#' for x in range(COLS)) for y in range(ROWS)]
zones=[''.join(zt[y]) for y in range(ROWS)]
js="/* Walkable overworld: 6 GPT panels stitched (4608x2048). Generated by tools/world_build/6_full_build.py */\nwindow.chapterFields=window.chapterFields||{};\nwindow.chapterFields.world="+json.dumps({'image':'story/maps/world.webp','tileSize':24,'displaySize':30,'stepMs':667,'walkCycleMs':480,'tiles':tiles,'zones':zones,'spawn':[sx,sy,0],'points':pts,'sites':meta},ensure_ascii=False,separators=(',',':'))+";\n"
os.makedirs(OUT,exist_ok=True)
open(OUT+'/world.js','w').write(js);M.save(OUT+'/world.webp',quality=82,method=6)
print('webp MB',round(os.path.getsize(OUT+'/world.webp')/1e6,2),'js KB',len(js)//1024)
vis=np.where(tw[:,:,None],np.array([240,240,240]),np.array([20,20,20])).astype(np.uint8)
v=Image.fromarray(vis).resize((COLS*8,ROWS*8),Image.NEAREST).convert('RGB')
v=Image.blend(v,M.resize(v.size),.5);d=ImageDraw.Draw(v)
for k,(a,b) in pts.items():d.ellipse([a*8-5,b*8-5,a*8+5,b*8+5],outline=(255,0,0),width=3)
v.save(OUT+'/mask.png')
