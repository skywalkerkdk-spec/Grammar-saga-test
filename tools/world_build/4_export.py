import numpy as np,json
from PIL import Image
Image.MAX_IMAGE_PIXELS=None
tw=np.load('/tmp/ow/tw3.npy');pts=json.load(open('/tmp/ow/points.json'));Z=np.load('/tmp/ow/Z.npy')
ROWS,COLS=tw.shape;T=48
S=json.load(open('/tmp/ow/sites_tile.json'))
# zones: mode per tile excluding safe '.'
letters=list('gfdclhsvwa')
zt=np.full((ROWS,COLS),'g',dtype='<U1')
for ty in range(ROWS):
    for tx in range(COLS):
        blk=Z[ty*T:(ty+1)*T,tx*T:(tx+1)*T].ravel()
        cnt={l:(blk==l).sum() for l in letters}
        best=max(cnt,key=cnt.get)
        if cnt[best]>0:zt[ty,tx]=best
# safe radius around sites
yy,xx=np.mgrid[0:ROWS,0:COLS]
for id_,(px,py) in pts.items():
    r=4 if id_.endswith('_t') else 3
    zt[(xx-px)**2+(yy-(py-1))**2<=r*r]='.'
# keep coast tiles: sea neighbors; fine
tiles=[''.join('.' if tw[y,x] else '#' for x in range(COLS)) for y in range(ROWS)]
zones=[''.join(zt[y]) for y in range(ROWS)]
from collections import Counter
print('zone counts on walkable',Counter(zt[tw].tolist()))
sx,sy=pts['d1'];spawn=[int(sx),int(sy),0]
meta={ s[0]:{'kind':s[1],'en':s[2],'ko':s[3]} for s in S}
js="/* Walkable overworld (GPT art, 3 panels stitched). Generated by tools/build_world.py */\nwindow.chapterFields=window.chapterFields||{};\nwindow.chapterFields.world="+json.dumps({'image':'story/maps/world.webp','tileSize':24,'tiles':tiles,'zones':zones,'spawn':spawn,'points':pts,'sites':meta},ensure_ascii=False,separators=(',',':'))+";\n"
open('/tmp/ow/world.js','w').write(js);print('world.js bytes',len(js))
W=Image.open('/tmp/ow/world_full.png').convert('RGB').resize((4608,1008),Image.LANCZOS)
W.save('/tmp/ow/world.webp',quality=76,method=6)
import os;print('world.webp MB',round(os.path.getsize('/tmp/ow/world.webp')/1e6,2))
